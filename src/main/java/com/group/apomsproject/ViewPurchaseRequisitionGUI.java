    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        try {
            // Ensure HeaderRegistry is initialized
            HeaderRegistry.init();

            // Initialize FileOperations
            FileOperations fileOps = new FileOperations();

            // Get table model for PurchaseRequisition using prs.csv
            DefaultTableModel model = fileOps.getTable("requisitions.csv");

            // Link model to JTable
            jTable1.setModel(model);
        } catch (Exception e) {
            JOptionPane.showMessageDialog(null, "Error loading Requisitions CSV file: " + e.getMessage());
        }
    }//GEN-LAST:event_jButton1ActionPerformed

    private void jButton2ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton2ActionPerformed
    try {
            // Ensure HeaderRegistry is initialized
            HeaderRegistry.init();

            // Get keyword from text field
            String keyword = jTextField1.getText();

            // Initialize Searching
            Searching searching = new Searching();

            // Search items.csv for Item class
            DefaultTableModel resultModel = searching.searchItems(keyword, "Requisition", "requisition.csv");

            // Link model to JTable
            jTable1.setModel(resultModel);
        } catch (Exception e) {
            JOptionPane.showMessageDialog(null, "Error: " + e.getMessage());
        }
    }//GEN-LAST:event_jButton2ActionPerformed

