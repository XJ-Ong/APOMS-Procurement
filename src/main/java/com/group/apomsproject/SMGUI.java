    private void btnSearchSpActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSearchSpActionPerformed
        String keyword = txtSpSearchField.getText().trim();

        if(keyword.isEmpty())
        {
            tableSorter.setRowFilter(null);
        }
        else
        {
            try
            {
                RowFilter<DefaultTableModel, Object> filter = RowFilter.regexFilter("(?i)" + keyword);
                tableSorter.setRowFilter(filter);

                if(tblSp.getRowCount() == 0)
                {
                    JOptionPane.showMessageDialog(this, "No matches found for: " + keyword);
                }
            }
            catch(Exception e)
            {
                tableSorter.setRowFilter(null);
                JOptionPane.showMessageDialog(this, "Invalid search keyword: " + e.getMessage());
            }
        }
    }//GEN-LAST:event_btnSearchSpActionPerformed

